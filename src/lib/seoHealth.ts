import { MIN_INDEXABLE_BIO_CHARS, bioLength } from "./profileCompleteness";
import { isGoogleMapsUrl } from "./googleMapsUrl";

// "Search visibility" for a clinic's public website: a plain-language checklist and a 0-100 score built
// only from data the admin already loads. Pure (no network, no React) so the dashboard card, the tests
// and any future page say the same thing. Google decides rankings; this lists what the owner controls.

export const SEO_TITLE_MAX = 60;
export const SEO_DESCRIPTION_MIN = 120;
export const SEO_DESCRIPTION_MAX = 160;
/** Reviews needed before the "reviews" check passes. */
export const SEO_MIN_REVIEWS = 3;

export type SeoGroup = "basics" | "doctors" | "trust" | "content" | "search";
export type SeoStatus = "pass" | "partial" | "fail" | "auto" | "unknown";

export interface SeoItem {
  id: string;
  group: SeoGroup;
  label: string;
  status: SeoStatus;
  /** Importance; 0 for items that never affect the score. */
  weight: number;
  /** Share of the weight earned, 0..1 (only meaningful for scored items). */
  credit: number;
  /** One line on the current state, e.g. "2 of 3 doctors". Optional. */
  detail?: string;
  /** Plain-language "how to fix" (also shown, in a calmer tone, for passing items as the reason it matters). */
  howToFix: string;
  /** Admin route that fixes it. */
  route: string;
  /** Whether the item counts towards the score. */
  scored: boolean;
}

export interface SeoDoctorLike {
  display_name?: string | null;
  photo_url?: string | null;
  bio?: string | null;
  is_active?: boolean | null;
}

export interface SeoHealthInput {
  profile: {
    clinic_name?: string | null;
    full_name?: string | null;
    display_name?: string | null;
    city?: string | null;
    address?: string | null;
    clinic_phone?: string | null;
    phone?: string | null;
    google_maps_url?: string | null;
    profile_photo_url?: string | null;
    bio?: string | null;
    slug?: string | null;
  } | null;
  settings: { seo_title?: string | null; seo_description?: string | null; hero_photo_url?: string | null } | null;
  /** Active doctors of the clinic. Fewer than 2 means a single-doctor clinic (the owner). */
  doctors?: SeoDoctorLike[] | null;
  /** null / undefined = not known yet (still loading or the lookup failed): the check is left out of the score. */
  counts?: {
    pricedServices?: number | null;
    reviews?: number | null;
    publishedPosts?: number | null;
    galleryPhotos?: number | null;
    openDays?: number | null;
  } | null;
}

export interface SeoHealth {
  /** 0-100. */
  score: number;
  level: "low" | "fair" | "good";
  items: SeoItem[];
  groups: { group: SeoGroup; title: string; items: SeoItem[] }[];
  /** The three most valuable fixes, biggest first. */
  nextActions: SeoItem[];
  isTeam: boolean;
}

const has = (v?: string | null) => (v ?? "").trim().length > 0;
const num = (v: number | null | undefined) => (typeof v === "number" && Number.isFinite(v) ? v : null);

/** Titles / descriptions the old save path stored for the owner: generated text, not a deliberate choice. */
export function isAutoGeneratedSeoTitle(v?: string | null): boolean {
  const t = (v ?? "").trim();
  return /^Dr\.?\s.+\|\s*Doctylia$/i.test(t);
}
export function isAutoGeneratedSeoDescription(v?: string | null): boolean {
  const t = (v ?? "").trim();
  return /^Book an appointment with Dr\.?\s/i.test(t)
    || /Book an appointment online and see timings, fees, services and patient reviews on Doctylia\.$/i.test(t);
}

export type SeoMode = "automatic" | "custom";
/** A blank or generated stored value is "Automatic"; anything else was written on purpose. */
export function seoTitleMode(v?: string | null): SeoMode {
  return has(v) && !isAutoGeneratedSeoTitle(v) ? "custom" : "automatic";
}
export function seoDescriptionMode(v?: string | null): SeoMode {
  return has(v) && !isAutoGeneratedSeoDescription(v) ? "custom" : "automatic";
}

/** "Dr. Anita Sharma" / "dr-anita-sharma" style: the address still carries a person's name. */
function slugLooksPersonal(slug: string, ownerName: string): boolean {
  const s = slug.toLowerCase();
  if (/^dr-/.test(s)) return true;
  const own = ownerName.toLowerCase().replace(/^dr\.?\s+/, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return own.length >= 3 && (s === own || s.startsWith(`${own}-`));
}

const GROUP_TITLES: Record<SeoGroup, string> = {
  basics: "Clinic details",
  doctors: "Doctors",
  trust: "Photos and reviews",
  content: "Things patients look for",
  search: "How you appear on Google",
};

const names = (list: SeoDoctorLike[]) => {
  const shown = list.slice(0, 3).map((d) => (d.display_name ?? "").trim() || "A doctor");
  const extra = list.length - shown.length;
  return shown.join(", ") + (extra > 0 ? ` and ${extra} more` : "");
};

export function computeSeoHealth(input: SeoHealthInput): SeoHealth {
  const p = input.profile ?? {};
  const s = input.settings ?? {};
  const counts = input.counts ?? {};
  const given = (input.doctors ?? []).filter((d) => d && d.is_active !== false);
  const isTeam = given.length >= 2;
  const ownerName = (p.display_name || p.full_name || "").trim();
  const doctors: SeoDoctorLike[] = isTeam ? given : [{ display_name: ownerName, photo_url: p.profile_photo_url, bio: p.bio }];

  const items: SeoItem[] = [];
  const add = (it: Omit<SeoItem, "scored" | "credit"> & { credit?: number; scored?: boolean }) =>
    items.push({ credit: it.status === "pass" || it.status === "auto" ? 1 : 0, scored: true, ...it });
  /** A check that depends on a count which may not be known yet. */
  const fromCount = (n: number | null, need: number) =>
    n === null ? { status: "unknown" as SeoStatus, credit: 0, scored: false }
      : n >= need ? { status: "pass" as SeoStatus, credit: 1, scored: true }
      : n > 0 ? { status: "partial" as SeoStatus, credit: n / need, scored: true }
      : { status: "fail" as SeoStatus, credit: 0, scored: true };

  // --- Clinic details
  const nameOk = isTeam ? has(p.clinic_name) : has(p.clinic_name) || has(ownerName);
  const cityOk = has(p.city);
  add({
    id: "name_city", group: "basics", label: "Clinic name and city", weight: 10,
    status: nameOk && cityOk ? "pass" : nameOk || cityOk ? "partial" : "fail",
    credit: nameOk && cityOk ? 1 : nameOk || cityOk ? 0.5 : 0,
    detail: !nameOk ? "Clinic name is missing" : !cityOk ? "City is missing" : undefined,
    howToFix: "Add your clinic name and city in Settings. People search for \"clinic in your city\", so these two are the first thing Google looks for.",
    route: "/admin/settings?tab=profile",
  });
  add({
    id: "address", group: "basics", label: "Clinic address", weight: 8, status: has(p.address) ? "pass" : "fail",
    howToFix: "Add the full street address in Settings so Google can show where you are and patients can find you.",
    route: "/admin/settings?tab=profile",
  });
  add({
    id: "phone", group: "basics", label: "Clinic phone number", weight: 6, status: has(p.clinic_phone) || has(p.phone) ? "pass" : "fail",
    howToFix: "Add the number patients should call in Settings. It appears on your page and in Google's listing.",
    route: "/admin/settings?tab=profile",
  });
  add({
    id: "maps", group: "basics", label: "Google Maps link", weight: 6, status: isGoogleMapsUrl(p.google_maps_url) ? "pass" : "fail",
    howToFix: "Paste your clinic's Google Maps link in Settings. It helps you show up in \"near me\" searches and gives patients one-tap directions.",
    route: "/admin/settings?tab=profile",
  });

  // --- Doctors
  const withPhoto = doctors.filter((d) => has(d.photo_url));
  const withBio = doctors.filter((d) => bioLength(d.bio) >= MIN_INDEXABLE_BIO_CHARS);
  const frac = (n: number) => (doctors.length ? n / doctors.length : 0);
  const doctorsRoute = isTeam ? "/admin/doctors" : "/admin/settings?tab=profile";
  const status = (n: number): SeoStatus => (n === doctors.length ? "pass" : n > 0 ? "partial" : "fail");
  add({
    id: "doctor_photos", group: "doctors", label: isTeam ? "Every doctor has a photo" : "Your profile photo", weight: 8,
    status: status(withPhoto.length), credit: frac(withPhoto.length),
    detail: isTeam && withPhoto.length < doctors.length ? `Missing for ${names(doctors.filter((d) => !has(d.photo_url)))}` : undefined,
    howToFix: "A clear photo of each doctor builds trust, and Google can show it next to your listing.",
    route: doctorsRoute,
  });
  add({
    id: "doctor_bios", group: "doctors",
    label: isTeam ? `Every doctor has a bio (${MIN_INDEXABLE_BIO_CHARS}+ characters)` : `A short bio (${MIN_INDEXABLE_BIO_CHARS}+ characters)`, weight: 12,
    status: status(withBio.length), credit: frac(withBio.length),
    detail: isTeam && withBio.length < doctors.length ? `Needs a longer bio: ${names(doctors.filter((d) => bioLength(d.bio) < MIN_INDEXABLE_BIO_CHARS))}` : undefined,
    howToFix: `Write a few sentences about your training and what you treat (at least ${MIN_INDEXABLE_BIO_CHARS} characters). A doctor page with no bio is kept out of Google.`,
    route: doctorsRoute,
  });

  // --- Photos and reviews
  const gallery = num(counts.galleryPhotos);
  const hasPhoto = has(s.hero_photo_url) || has(p.profile_photo_url) || (gallery ?? 0) > 0;
  add({
    id: "photo", group: "trust", label: "Clinic or profile photo", weight: 8, status: hasPhoto ? "pass" : gallery === null ? "unknown" : "fail",
    scored: hasPhoto || gallery !== null,
    howToFix: "Add a photo of your clinic or yourself on My Website. Pages with a real photo get clicked more and look better when shared.",
    route: "/admin/my-website",
  });
  add({
    id: "reviews", group: "trust", label: `At least ${SEO_MIN_REVIEWS} patient reviews`, weight: 8, ...fromCount(num(counts.reviews), SEO_MIN_REVIEWS),
    detail: num(counts.reviews) === null ? undefined : `${num(counts.reviews)} so far`,
    howToFix: "Ask happy patients to leave a review. Reviews are the strongest trust signal on your page.",
    route: "/admin/reviews",
  });

  // --- What patients look for
  add({
    id: "services", group: "content", label: "At least one service with a price", weight: 8, ...fromCount(num(counts.pricedServices), 1),
    howToFix: "List what you offer with the fee on My Website. Patients search for a treatment and its cost.",
    route: "/admin/my-website",
  });
  const openDays = num(counts.openDays);
  add({
    id: "hours", group: "content", label: "Opening hours", weight: 8, ...fromCount(openDays, 1),
    howToFix: isTeam ? "Set each doctor's working days on the Doctors page. Google shows opening hours next to your listing." : "Set your working days on My Website. Google shows opening hours next to your listing.",
    route: isTeam ? "/admin/doctors" : "/admin/my-website",
  });
  add({
    id: "articles", group: "content", label: "At least one published health article", weight: 8, ...fromCount(num(counts.publishedPosts), 1),
    howToFix: "Publish one short article answering a question patients often ask. It gives Google something to find you for.",
    route: "/admin/blog",
  });

  // --- How you appear on Google
  const titleCustom = seoTitleMode(s.seo_title) === "custom";
  const descCustom = seoDescriptionMode(s.seo_description) === "custom";
  add({
    id: "seo_custom", group: "search", label: "Title and description on Google", weight: 0, scored: false,
    status: titleCustom || descCustom ? "pass" : "auto",
    detail: titleCustom || descCustom ? "Custom" : "Automatic",
    howToFix: "Automatic is fine: we build them from your clinic name and city. Write your own on My Website only if you want to.",
    route: "/admin/my-website",
  });
  if (titleCustom) {
    const n = (s.seo_title ?? "").trim().length;
    add({
      id: "seo_title_length", group: "search", label: `Custom title is ${SEO_TITLE_MAX} characters or fewer`, weight: 2,
      status: n <= SEO_TITLE_MAX ? "pass" : "partial", credit: n <= SEO_TITLE_MAX ? 1 : 0.5, detail: `${n} characters`,
      howToFix: `Google cuts titles longer than about ${SEO_TITLE_MAX} characters. Shorten yours so patients see all of it.`,
      route: "/admin/my-website",
    });
  }
  if (descCustom) {
    const n = (s.seo_description ?? "").trim().length;
    const ok = n >= SEO_DESCRIPTION_MIN && n <= SEO_DESCRIPTION_MAX;
    add({
      id: "seo_description_length", group: "search", label: `Custom description is ${SEO_DESCRIPTION_MIN} to ${SEO_DESCRIPTION_MAX} characters`, weight: 2,
      status: ok ? "pass" : "partial", credit: ok ? 1 : 0.5, detail: `${n} characters`,
      howToFix: `Aim for ${SEO_DESCRIPTION_MIN} to ${SEO_DESCRIPTION_MAX} characters: shorter looks thin, longer gets cut off.`,
      route: "/admin/my-website",
    });
  }
  if (isTeam) {
    const slug = (p.slug ?? "").trim();
    const personal = !!slug && slugLooksPersonal(slug, ownerName);
    // Nothing for the owner to do: the database switches a team clinic to its clinic-name address by itself.
    add({
      id: "slug", group: "search", label: "Website address uses the clinic name", weight: 6,
      status: !slug ? "fail" : personal ? "auto" : "pass",
      detail: !slug ? undefined : personal ? `Switches automatically (doctylia.com/dr/${slug})` : `doctylia.com/dr/${slug}`,
      scored: !!slug && !personal,
      howToFix: "Your address changes to your clinic name automatically when you have more than one doctor. Old links keep working.",
      route: "/admin/settings?tab=profile",
    });
  }

  const scored = items.filter((i) => i.scored && i.weight > 0);
  const total = scored.reduce((a, i) => a + i.weight, 0);
  const earned = scored.reduce((a, i) => a + i.weight * i.credit, 0);
  const score = total ? Math.round((earned / total) * 100) : 0;

  const nextActions = scored
    .filter((i) => i.credit < 1)
    .map((i, idx) => ({ i, gain: i.weight * (1 - i.credit), idx }))
    .sort((a, b) => b.gain - a.gain || a.idx - b.idx)
    .slice(0, 3)
    .map((x) => x.i);

  const order: SeoGroup[] = ["basics", "doctors", "trust", "content", "search"];
  return {
    score,
    level: score >= 80 ? "good" : score >= 50 ? "fair" : "low",
    items,
    groups: order.map((g) => ({ group: g, title: GROUP_TITLES[g], items: items.filter((i) => i.group === g) })).filter((g) => g.items.length),
    nextActions,
    isTeam,
  };
}

export const SEO_STATUS_LABEL: Record<SeoStatus, string> = {
  pass: "Done", partial: "Almost", fail: "To do", auto: "Automatic", unknown: "Checking",
};

export const seoNudgeKey = (clinicId: string) => `doctylia:seo-nudge-dismissed:${clinicId}`;
export function isSeoNudgeDismissed(clinicId: string): boolean {
  try { return window.localStorage.getItem(seoNudgeKey(clinicId)) === "1"; } catch { return false; }
}
export function setSeoNudgeDismissed(clinicId: string, dismissed: boolean): void {
  try {
    if (dismissed) window.localStorage.setItem(seoNudgeKey(clinicId), "1");
    else window.localStorage.removeItem(seoNudgeKey(clinicId));
  } catch { /* private mode: the list simply shows again */ }
}
