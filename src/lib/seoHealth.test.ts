import { describe, it, expect } from "vitest";
import { MIN_INDEXABLE_BIO_CHARS as CLINIC_TEAM_MIN } from "./seo/clinicTeam";
import { MIN_INDEXABLE_BIO_CHARS } from "./profileCompleteness";
import {
  computeSeoHealth, isAutoGeneratedSeoDescription, isAutoGeneratedSeoTitle, seoDescriptionMode, seoTitleMode,
  type SeoHealthInput,
} from "./seoHealth";

const bio = "b".repeat(80);
const fullProfile = {
  clinic_name: "Sunrise Clinic", full_name: "Anita Sharma", city: "Kota", address: "12 Main Road", clinic_phone: "9999999999",
  google_maps_url: "https://maps.google.com/?q=x", profile_photo_url: "p.jpg", bio, slug: "sunrise-clinic",
};
const fullCounts = { pricedServices: 2, reviews: 5, publishedPosts: 1, galleryPhotos: 3, openDays: 5 };
const full = (over: Partial<SeoHealthInput> = {}): SeoHealthInput => ({ profile: fullProfile, settings: { hero_photo_url: "h.jpg" }, doctors: [], counts: fullCounts, ...over });
const doc = (n: number, over: Record<string, unknown> = {}) => ({ display_name: `Dr ${n}`, photo_url: "x", bio, is_active: true, ...over });
const byId = (h: ReturnType<typeof computeSeoHealth>, id: string) => h.items.find((i) => i.id === id)!;

describe("seoHealth", () => {
  it("pins the bio threshold to the edge value", () => {
    expect(MIN_INDEXABLE_BIO_CHARS).toBe(60);
    expect(CLINIC_TEAM_MIN).toBe(60);
  });

  it("scores a complete single-doctor clinic 100 with no actions", () => {
    const h = computeSeoHealth(full());
    expect(h.score).toBe(100);
    expect(h.level).toBe("good");
    expect(h.nextActions).toEqual([]);
    expect(h.isTeam).toBe(false);
    expect(h.items.find((i) => i.id === "slug")).toBeUndefined();
  });

  it("handles no data at all without throwing", () => {
    const h = computeSeoHealth({ profile: null, settings: null });
    expect(h.score).toBe(0);
    expect(h.level).toBe("low");
    expect(h.nextActions).toHaveLength(3);
    expect(h.groups.length).toBeGreaterThan(0);
  });

  it("leaves unknown counts out of the score instead of failing them", () => {
    const h = computeSeoHealth(full({ counts: {} }));
    expect(byId(h, "reviews").status).toBe("unknown");
    expect(h.score).toBe(100);
  });

  it("gives partial credit for 1-2 reviews", () => {
    const h = computeSeoHealth(full({ counts: { ...fullCounts, reviews: 1 } }));
    expect(byId(h, "reviews").status).toBe("partial");
    expect(h.score).toBeLessThan(100);
    expect(h.nextActions[0].id).toBe("reviews");
  });

  it("treats a short bio as failing and a missing maps link as failing", () => {
    const h = computeSeoHealth(full({ profile: { ...fullProfile, bio: "short", google_maps_url: "" } }));
    expect(byId(h, "doctor_bios").status).toBe("fail");
    expect(byId(h, "maps").status).toBe("fail");
    expect(byId(h, "maps").howToFix).toMatch(/near me/i);
  });

  it("checks every active doctor in a team clinic and ignores inactive ones", () => {
    const docs = [doc(1), doc(2, { bio: "tiny" }), doc(3, { photo_url: "" }), doc(4, { is_active: false, bio: "" })];
    const h = computeSeoHealth(full({ doctors: docs }));
    expect(h.isTeam).toBe(true);
    expect(byId(h, "doctor_bios").status).toBe("partial");
    expect(byId(h, "doctor_bios").detail).toContain("Dr 2");
    expect(byId(h, "doctor_bios").detail).not.toContain("Dr 4");
    expect(byId(h, "doctor_photos").detail).toContain("Dr 3");
    expect(byId(h, "doctor_bios").route).toBe("/admin/doctors");
  });

  it("caps the doctor names in the detail for 9+ doctors", () => {
    const docs = Array.from({ length: 9 }, (_, i) => doc(i, { bio: "" }));
    const h = computeSeoHealth(full({ doctors: docs }));
    expect(byId(h, "doctor_bios").status).toBe("fail");
    expect(byId(h, "doctor_bios").detail).toContain("and 6 more");
  });

  it("never asks the owner to change a personal address by hand: team clinics pass or show a neutral 'switches automatically' note", () => {
    const docs = [doc(1), doc(2)];
    for (const slug of ["dr-anita-sharma", "anita-sharma-kota"]) {
      const h = computeSeoHealth(full({ doctors: docs, profile: { ...fullProfile, slug } }));
      const item = byId(h, "slug");
      expect(item.status).toBe("auto");
      expect(item.scored).toBe(false);
      expect(item.detail).toMatch(/switches automatically/i);
      expect(item.howToFix).not.toMatch(/Settings|Switch it/);
      expect(h.nextActions.map((i) => i.id)).not.toContain("slug");
    }
    const ok = computeSeoHealth(full({ doctors: docs }));
    expect(byId(ok, "slug").status).toBe("pass");
    const single = computeSeoHealth(full({ profile: { ...fullProfile, slug: "dr-anita-sharma" } }));
    expect(single.items.find((i) => i.id === "slug")).toBeUndefined();
  });

  it("treats blank and generated SEO text as automatic (neutral, not scored)", () => {
    const h = computeSeoHealth(full({ settings: { hero_photo_url: "h", seo_title: "Dr. A Sharma - ENT in Kota | Doctylia", seo_description: "Book an appointment with Dr. A Sharma, ENT in Kota." } }));
    expect(byId(h, "seo_custom").status).toBe("auto");
    expect(byId(h, "seo_custom").scored).toBe(false);
    expect(h.items.find((i) => i.id === "seo_title_length")).toBeUndefined();
    expect(h.score).toBe(100);
  });

  it("warns (never fails) on custom values outside the guidance", () => {
    const h = computeSeoHealth(full({ settings: { hero_photo_url: "h", seo_title: "T".repeat(90), seo_description: "short custom" } }));
    expect(byId(h, "seo_custom").status).toBe("pass");
    expect(byId(h, "seo_title_length").status).toBe("partial");
    expect(byId(h, "seo_description_length").status).toBe("partial");
    expect(h.score).toBeGreaterThan(90);
    const good = computeSeoHealth(full({ settings: { hero_photo_url: "h", seo_title: "T".repeat(55), seo_description: "d".repeat(140) } }));
    expect(good.score).toBe(100);
  });

  it("detects generated titles and descriptions", () => {
    expect(isAutoGeneratedSeoTitle("Dr. Anita Sharma - ENT in Kota | Doctylia")).toBe(true);
    expect(isAutoGeneratedSeoTitle("Sunrise Clinic | Doctylia")).toBe(false);
    expect(isAutoGeneratedSeoTitle("Best ENT in Kota")).toBe(false);
    expect(isAutoGeneratedSeoDescription("Book an appointment with Dr. A, ENT in Kota. Clinic timings...")).toBe(true);
    expect(isAutoGeneratedSeoDescription("We treat ear problems.")).toBe(false);
    expect(seoTitleMode("  ")).toBe("automatic");
    expect(seoTitleMode("My title")).toBe("custom");
    expect(seoDescriptionMode(null)).toBe("automatic");
  });

  it("returns at most three actions, biggest gain first", () => {
    const h = computeSeoHealth({ profile: { ...fullProfile, address: "", clinic_phone: "", bio: "" }, settings: null, counts: { ...fullCounts, reviews: 0, publishedPosts: 0 } });
    expect(h.nextActions).toHaveLength(3);
    expect(h.nextActions[0].id).toBe("doctor_bios");
  });
});
