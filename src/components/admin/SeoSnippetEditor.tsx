import { AlertCircle, CheckCircle2, RotateCcw } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import {
  SEO_DESCRIPTION_MAX, SEO_DESCRIPTION_MIN, SEO_TITLE_MAX,
  isAutoGeneratedSeoDescription, isAutoGeneratedSeoTitle, seoDescriptionMode, seoTitleMode,
} from "@/lib/seoHealth";

interface Props {
  /** The stored values exactly as saved ("" = automatic). */
  title: string;
  description: string;
  /** What the public page uses when the stored value is blank (from the shared builder). */
  autoTitle: string;
  autoDescription: string;
  /** Clinic address shown in the Google-style preview, e.g. "doctylia.com/dr/sunrise-clinic". */
  displayUrl: string;
  disabled?: boolean;
  /** Clears a stored value. The parent writes it and reports a failure. */
  onReset: (key: "seo_title" | "seo_description") => void;
  resetting?: "seo_title" | "seo_description" | null;
  onChange: (key: "seo_title" | "seo_description", value: string) => void;
}

const clip = (s: string, max: number) => (s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s);

const ModeBadge = ({ mode }: { mode: "automatic" | "custom" }) => (
  <span className="rounded-full border border-border bg-secondary px-2 py-0.5 text-[11px] font-medium text-foreground">
    {mode === "custom" ? "Custom" : "Automatic"}
  </span>
);

/** Counter line: the number is always written out and the guidance is words, never colour alone. */
const Counter = ({ id, n, min, max }: { id: string; n: number; min?: number; max: number }) => {
  const over = n > max;
  const under = min !== undefined && n > 0 && n < min;
  return (
    <p id={id} className="text-xs text-muted-foreground tabular-nums">
      <span className={over || under ? "font-semibold text-warning" : ""}>{n} of {max} characters</span>
      {over && " - too long, Google will cut the end off"}
      {under && ` - aim for ${min} to ${max}`}
      {!over && !under && n > 0 && " - good length"}
    </p>
  );
};

const SeoSnippetEditor = ({ title, description, autoTitle, autoDescription, displayUrl, disabled, onReset, resetting, onChange }: Props) => {
  const titleMode = seoTitleMode(title);
  const descMode = seoDescriptionMode(description);
  // A stored value that looks generated is treated as automatic by the public page, so the preview shows the automatic text.
  const shownTitle = titleMode === "custom" ? title.trim() : autoTitle;
  const shownDesc = descMode === "custom" ? description.trim() : autoDescription;
  const titleGenerated = isAutoGeneratedSeoTitle(title);
  const descGenerated = isAutoGeneratedSeoDescription(description);

  const resetButton = (key: "seo_title" | "seo_description", label: string) => (
    <Button type="button" size="sm" variant="outline" className="h-9 gap-1.5" disabled={disabled || resetting === key} onClick={() => onReset(key)}>
      <RotateCcw className="h-3.5 w-3.5" aria-hidden="true" /> {resetting === key ? "Resetting..." : label}
    </Button>
  );

  return (
    <div className="space-y-4" data-testid="seo-snippet-editor">
      <p className="text-xs text-muted-foreground">
        Google decides what it shows. Leave these on Automatic and we write them from your clinic name and city. Write your own only if you want to.
      </p>

      <div className="space-y-1.5">
        <div className="flex items-center justify-between gap-2">
          <Label htmlFor="seo-title">Page title</Label>
          <ModeBadge mode={titleMode} />
        </div>
        {titleGenerated && (
          <div role="note" className="flex flex-col gap-2 rounded-lg border border-warning/30 bg-warning/10 p-3 text-xs sm:flex-row sm:items-center">
            <p className="flex-1 text-foreground">
              <AlertCircle className="mr-1 inline h-3.5 w-3.5 text-warning" aria-hidden="true" />
              This title was generated automatically from the doctor's name. Reset it to use your clinic name.
            </p>
            {resetButton("seo_title", "Reset title")}
          </div>
        )}
        <Input
          id="seo-title" value={title} disabled={disabled} maxLength={100}
          onChange={(e) => onChange("seo_title", e.target.value)}
          placeholder={autoTitle || "Automatic"} aria-describedby="seo-title-count"
        />
        <Counter id="seo-title-count" n={titleGenerated ? 0 : title.trim().length} max={SEO_TITLE_MAX} />
        {titleMode === "custom" && <div>{resetButton("seo_title", "Reset to automatic")}</div>}
      </div>

      <div className="space-y-1.5">
        <div className="flex items-center justify-between gap-2">
          <Label htmlFor="seo-description">Page description</Label>
          <ModeBadge mode={descMode} />
        </div>
        {descGenerated && (
          <div role="note" className="flex flex-col gap-2 rounded-lg border border-warning/30 bg-warning/10 p-3 text-xs sm:flex-row sm:items-center">
            <p className="flex-1 text-foreground">
              <AlertCircle className="mr-1 inline h-3.5 w-3.5 text-warning" aria-hidden="true" />
              This description was generated automatically from the doctor's details. Reset it to use your clinic's.
            </p>
            {resetButton("seo_description", "Reset description")}
          </div>
        )}
        <Textarea
          id="seo-description" rows={3} value={description} disabled={disabled} maxLength={200}
          onChange={(e) => onChange("seo_description", e.target.value)}
          placeholder={autoDescription || "Automatic"} aria-describedby="seo-description-count"
        />
        <Counter id="seo-description-count" n={descGenerated ? 0 : description.trim().length} min={SEO_DESCRIPTION_MIN} max={SEO_DESCRIPTION_MAX} />
        {descMode === "custom" && <div>{resetButton("seo_description", "Reset to automatic")}</div>}
      </div>

      <div>
        <p className="mb-1.5 flex items-center gap-1.5 text-xs font-medium text-foreground">
          <CheckCircle2 className="h-3.5 w-3.5 text-success" aria-hidden="true" /> How it can look on Google
        </p>
        <div className="rounded-lg border border-border bg-card p-3" aria-label="Google result preview" role="group">
          <p className="truncate text-xs text-muted-foreground">{displayUrl}</p>
          <p className="mt-0.5 break-words text-base font-medium leading-snug text-royal" data-testid="seo-preview-title">
            {clip(shownTitle, SEO_TITLE_MAX) || "Your page title"}
          </p>
          <p className="mt-0.5 break-words text-sm text-muted-foreground" data-testid="seo-preview-description">
            {clip(shownDesc, SEO_DESCRIPTION_MAX) || "Your page description"}
          </p>
        </div>
        <p className="mt-1 text-[11px] text-muted-foreground">A preview only: Google may show something different.</p>
      </div>
    </div>
  );
};

export default SeoSnippetEditor;
